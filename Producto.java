package modulo;

import javax.swing.JOptionPane;

/**
 *
 * @author Monserrath
 */
public class Producto {

    private int codigo;
    private String nombre;
    private double precio;
    private int cantidadDisponible;

    public Producto() {
    }

    public Producto(int codigo, String nombre, double precio, int cantidadDisponible) {
        this.codigo = codigo;
        this.nombre = nombre;
        this.precio = precio;
        this.cantidadDisponible = cantidadDisponible;
    }

    public int getCodigo() {
        return codigo;
    }

    public void setCodigo(int codigo) {
        this.codigo = codigo;
    }

    public String getNombre() {
        return nombre;
    }

    public void setNombre(String nombre) {
        this.nombre = nombre;
    }

    public double getPrecio() {
        return precio;
    }

    public void setPrecio(double precio) {
        this.precio = precio;
    }

    public int getCantidadDisponible() {
        return cantidadDisponible;
    }

    public void setCantidadDisponible(int cantidadDisponible) {
        this.cantidadDisponible = cantidadDisponible;
    }

    public void informacionProducto(){
        JOptionPane.showMessageDialog(null, "Información del prodcuto"
                + "\nNombre: " + nombre
                + "\nCodigo: " + codigo
                + "\nPrecio: " + precio
                + "\nCantidad disponible: " +cantidadDisponible);
    }
    
    
}
